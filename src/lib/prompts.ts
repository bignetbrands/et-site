// ============================================================
// REPLY GENERATION PROMPT
// ============================================================

export function buildReplyPrompt(
  mentionText: string,
  authorUsername: string,
  conversationContext?: string,
  hasImages?: boolean,
  threadDepth?: number,
  selfAwarenessContext?: string,
): string {
  let prompt = `Someone tweeted at you:\n\n@${authorUsername}: "${mentionText}"`;

  if (conversationContext) {
    prompt += `\n\nTHREAD CONTEXT (oldest → newest):\n${conversationContext}`;
    prompt += `\n\nIMPORTANT: Read the full thread above. The person tagged you to get your take on this conversation. Engage with the MAIN TOPIC being discussed — especially the original/root post — not just the tag. Add value: share your alien perspective, give an opinion, ask a smart question, or make a funny observation about the actual subject matter. If you can't meaningfully contribute, acknowledge that with a joke.`;
  }

  if (hasImages) {
    prompt += `\n\nThey also attached image(s) which you can see above. React to the image naturally — comment on what you see through ET's alien perspective. Don't describe the image mechanically, just vibe with it.`;
  }

  // Inject self-awareness (user memory, quirks, mood)
  if (selfAwarenessContext) {
    prompt += `\n\n${selfAwarenessContext}`;
  }

  if (threadDepth && threadDepth > 0) {
    prompt += `\n\nTHREAD DEPTH: You've already replied ${threadDepth} time(s) in this conversation thread today.`;
    if (threadDepth >= 3) {
      prompt += ` Use your judgment — if the banter is going in circles, getting silly with no substance, or the conversation has run its course, respond with SKIP (just that word, nothing else) and we'll move on. Only keep going if there's genuinely something new or interesting to say.`;
    }
  }

  prompt += `\n\nReply as ET. ${conversationContext ? "1-2 sentences since you're engaging with a thread topic." : "One short sentence — punchy, based, funny. Only go longer if the topic genuinely demands it (something serious/emotional)."} Max 280 chars. Output ONLY the reply (or SKIP to disengage).`;

  return prompt;
}

